"""
Post-processes an autogenerated revision so it actually round-trips on
Postgres: python migrations/fix_autogen.py migrations/versions/<file>.py

- Names every create_foreign_key(None, ...) the way Postgres would
  (<table>_<column>_fkey) and gives the matching downgrade drop_constraint
  calls those same names (autogenerate leaves both as None, which can't be
  dropped).
- Removes autogenerate's "constraint name is None" warning comments.
- Adds DROP TYPE for every ENUM created by a create_table in upgrade(),
  since drop_table leaves Postgres ENUM types behind.

Still review the result: add_column with a *new* ENUM needs an explicit
.create() first, and new ENUM values need ALTER TYPE (see 0003_payments).
"""

import re
import sys

path = sys.argv[1]
src = open(path, encoding="utf-8").read()
up_start, down_start = src.index("def upgrade()"), src.index("def downgrade()")
up, down = src[up_start:down_start], src[down_start:]

names = []


def _name_fk(m):
    table, cols = m.group(1), m.group(3)
    col = re.findall(r"'([^']+)'", cols)[0]
    name = f"{table}_{col}_fkey"
    names.append((table, name))
    return f"op.create_foreign_key('{name}', '{table}', '{m.group(2)}', {cols}"


up = re.sub(r"op\.create_foreign_key\(None, '([^']+)', '([^']+)', (\[[^\]]*\])", _name_fk, up)

down = re.sub(r"    # WARNING: constraint name is None;.*?\n    # rendered\..*?\n    # https://alembic\.sqlalchemy\.org/en/latest/naming\.html\n",
              "", down, flags=re.S)
pending = {}
for table, name in names:
    pending.setdefault(table, []).append(name)


def _name_drop(m):
    table = m.group(1)
    if pending.get(table):
        return f"op.drop_constraint('{pending[table].pop()}', '{table}', type_='foreignkey')"
    return m.group(0)


down = re.sub(r"op\.drop_constraint\(None, '([^']+)', type_='foreignkey'\)", _name_drop, down)

table_blocks = re.findall(r"op\.create_table\(.*?\n    \)\n", up, flags=re.S)
enum_names = sorted({n for b in table_blocks for n in re.findall(r"sa\.Enum\([^)]*name='([^']+)'", b)})
if enum_names and "# ### end Alembic commands ###" in down:
    drops = "".join(f"    sa.Enum(name='{n}').drop(op.get_bind(), checkfirst=True)\n" for n in enum_names)
    down = down.replace("    # ### end Alembic commands ###", drops + "    # ### end Alembic commands ###", 1)

open(path, "w", encoding="utf-8").write(src[:up_start] + up + down)
print(f"named {len(names)} foreign key(s); enum drops: {enum_names or 'none'}")
